const MODEL_MAP: ReadonlyMap<string, ModelInfo> = new Map(
  MODEL_CATALOG.map((m) => [m.id, m])
);

/**
 * Retrieves static model information for a given model ID.
 */
export function getModelInfo(modelId: string): ModelInfo | undefined {
  return MODEL_MAP.get(modelId);
}

/**
 * Returns all models for a specific provider.
 */
export function getModelsByProvider(provider: ProviderId): ModelInfo[] {
  return MODEL_CATALOG.filter((m) => m.provider === provider);
}

/**
 * Returns all embedding models, optionally filtered by provider.
 */
export function getEmbeddingModels(provider?: EmbeddingProviderId): ModelInfo[] {
  return MODEL_CATALOG.filter((m) => {
    if (!m.isEmbedding) return false;
    return provider ? m.provider === provider : true;
  });
}

/**
 * Gets the default chat model for a provider.
 */
export function getDefaultChatModel(provider: ProviderId): string {
  return PROVIDER_METADATA[provider].defaultChatModel;
}

/**
 * Gets the default fast indexing model for a provider.
 */
export function getDefaultFastModel(provider: ProviderId): string {
  return PROVIDER_METADATA[provider].defaultFastModel;
}

/**
 * Gets the default embedding model for an embedding provider.
 */
export function getDefaultEmbeddingModel(provider: EmbeddingProviderId): string {
  const meta = PROVIDER_METADATA[provider];
  return meta.defaultEmbeddingModel ?? (provider === 'OPENAI' ? 'text-embedding-3-small' : 'gemini-embedding-001');
}
